export const toHookSummary = (h: HookDetail): HookSummary => {
  const onChain = hookDraftToOnChain({
    id: h.id,
    protocol: h.protocol,
    protocolName: h.protocolName,
    label: h.label,
    description: h.description,
    kind: h.kind === 'seat' ? 'seat' : 'flow',
    targetProgram: h.targetProgram,
    instructionName: h.instructionName,
    discriminator: h.discriminator,
    dataTemplate: {
      baseHex: h.dataTemplate.baseHex,
      slots: h.dataTemplate.slots.map((s) => ({
        name: s.name,
        kind: (s.kind === 'amount_in' || s.kind === 'min_out' || s.kind === 'seat_arg' ? s.kind : 'caller_arg') as 'amount_in' | 'min_out' | 'caller_arg' | 'seat_arg',
        offset: s.offset,
        length: s.length,
        type: (s.type === 'u8' || s.type === 'u16' || s.type === 'u32' || s.type === 'u64' || s.type === 'u128' || s.type === 'bool' || s.type === 'pubkey' ? s.type : 'bytes') as 'u8' | 'u16' | 'u32' | 'u64' | 'u128' | 'bool' | 'pubkey' | 'bytes',
      })),
    },
    accountsTemplate: h.accountsTemplate.map((a) => ({
      index: a.index,
      name: a.name,
      role: (a.role === 'fixed' || a.role === 'stage_authority' || a.role === 'stage_in' || a.role === 'stage_out' || a.role === 'seat_pda' || a.role === 'program' || a.role === 'sysvar' || a.role === 'payer' ? a.role : 'caller_supplied') as 'fixed' | 'stage_authority' | 'stage_in' | 'stage_out' | 'seat_pda' | 'caller_supplied' | 'program' | 'sysvar' | 'payer',
      address: a.address ?? null,
      writable: a.writable,
      signer: a.signer,
    })),
    companionInstructions: h.companionInstructions.map((c) => ({
      programId: c.programId,
      instructionName: c.instructionName,
      discriminator: c.discriminator,
      position: c.position === 'after' ? 'after' : 'before',
    })),
    mintIn: h.mintIn,
    mintOut: h.mintOut,
  })
  return {
    id: h.id,
    address: h.address,
    protocol: h.protocol,
    protocolName: h.protocolName,
    label: h.label,
    description: h.description,
    kind: h.kind,
    targetProgram: h.targetProgram,
    instructionName: h.instructionName,
    mintIn: h.mintIn,
    mintOut: h.mintOut,
    mintInConstraint: h.mintInConstraint ?? onChain.mintIn,
    mintOutConstraint: h.mintOutConstraint ?? onChain.mintOut,
    wrapSolIn: h.wrapSolIn ?? (h.id === 'jupiter.swap'),
    unwrapSolOut: h.unwrapSolOut ?? (h.id === 'jupiter.swap'),
    assetInSymbol: h.assetInSymbol,
    assetOutSymbol: h.assetOutSymbol,
    author: h.author,
    authorShareBps: h.authorShareBps,
    immutable: h.immutable,
    sdkCall: h.sdkCall,
    stats: h.stats,
    publishedAt: h.publishedAt,
  }
}

