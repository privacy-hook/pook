export type FixtureErrorBody<Code extends string = string> = {
  error: Omit<ApiErrorBody<Code>['error'], 'stage'> & { stage: KnownErrorStage }
}

export type ErrorDetails<Code extends string> = Record<Code, readonly [message: string, retryable: boolean, stage: KnownErrorStage]>

export function fixtureErrors<Code extends string>(
  details: ErrorDetails<Code>,
  extra: Partial<Record<Code, Partial<Omit<FixtureErrorBody['error'], 'code'>>>> = {},
): Record<Code, FixtureErrorBody<Code>> {
  const out = {} as Record<Code, FixtureErrorBody<Code>>
  for (const code of Object.keys(details) as Code[]) {
    const [message, retryable, stage] = details[code]
    out[code] = { error: { code, message, retryable, stage, ...extra[code] } }
  }
  return out
}

